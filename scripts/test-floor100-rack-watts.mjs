import assert from "node:assert/strict";
import {buildFloor100PowerModel,validateFloor100RackWatts,FLOOR100_RACK_BASELINE_MAX_W} from "../floor100-power.mjs";
import {buildFloor100FeedAllocation} from "../floor100-feed-allocation.mjs";
const racks=Array.from({length:100},(_,i)=>({id:"R"+String(i+1).padStart(3,"0"),row:Math.floor(i/10),column:i%10,kind:i%10<8?"compute":i%10===8?"fabric":"storage"}));
const ids=racks.map(r=>r.id),initial=buildFloor100PowerModel(racks);
assert.equal(FLOOR100_RACK_BASELINE_MAX_W,250000);
assert.equal(initial.totalW,10020000);
assert.equal(initial.entries[0].baselineW,120000);
assert.equal(initial.customizedRacks,0);
assert.deepEqual(initial.customOverrides,{});
const input={R001:180000,R009:30000,R100:0};
const unchanged=JSON.stringify(input);
const preset=validateFloor100RackWatts(input,ids);
assert.deepEqual({...preset},input);
assert.equal(JSON.stringify(input),unchanged);
const edited=buildFloor100PowerModel(racks,100,1.2,preset);
assert.equal(edited.customizedRacks,3);
assert.equal(edited.entries[0].estimatedW,180000);
assert.equal(edited.entries[0].customBaseline,true);
assert.equal(edited.entries[0].peakW,180000);
assert.equal(edited.entries[8].estimatedW,30000);
assert.equal(edited.entries[99].estimatedW,0);
assert.equal(edited.totalW,10020000+60000+12000-24000);
assert.equal(edited.rows[0].estimatedW,1002000+60000+12000);
assert.equal(edited.rows[9].estimatedW,1002000-24000);
assert.equal(edited.facilityW,Math.round(edited.totalW*1.2));
assert.equal(edited.rows.reduce((s,r)=>s+r.estimatedW,0),edited.totalW);
assert.equal(buildFloor100FeedAllocation(edited,"normal").demandKW,edited.totalKW);
const scaled=buildFloor100PowerModel(racks,80,1.2,input);
assert.equal(scaled.entries[0].estimatedW,144000);
assert.equal(scaled.entries[8].estimatedW,24000);
assert.equal(scaled.totalW,Math.round(edited.totalW*.8));
assert.equal(initial.totalW,10020000);
assert.equal(JSON.stringify(input),unchanged);
assert.deepEqual({...validateFloor100RackWatts({},ids)},{});
for(const bad of [{R001:-100},{R001:250100},{R001:100001},{R001:120.5},{R001:NaN},{R001:"120000"},{R999:10000}])
 assert.throws(()=>validateFloor100RackWatts(bad,ids),RangeError);
assert.throws(()=>validateFloor100RackWatts(Object.fromEntries([["__proto__",100]]),ids),RangeError);
assert.throws(()=>validateFloor100RackWatts(null,ids),RangeError);
assert.throws(()=>validateFloor100RackWatts([],ids),RangeError);
assert.throws(()=>buildFloor100PowerModel(racks,100,1.2,{R001:250001}),RangeError);
console.log(JSON.stringify({status:"PASS",racks:100,editedRacks:edited.customizedRacks,watts:edited.totalW,scaledWatts:scaled.totalW,transactional:true,source:"DEMO user-adjustable baseline only"}));
