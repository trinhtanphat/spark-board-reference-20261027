import assert from 'node:assert/strict';
import {buildFloor100Impact,FLOOR100_ROUTE_SCENARIOS} from '../floor100-impact.mjs';
const racks=Array.from({length:100},(_,i)=>({id:'R'+String(i+1).padStart(3,'0'),row:Math.floor(i/10),column:i%10,kind:i%10<8?'compute':i%10===8?'fabric':'storage'}));
const before=JSON.stringify(racks);
const expectCount=(mode,visible,dimmed,unmapped)=>{
 const x=buildFloor100Impact(racks,mode);
 assert.deepEqual(x.counts,{visible,dimmed,unmapped});
 assert.equal(x.entries.length,100);
 assert.equal(x.rows.length,10);
 assert.ok(x.rows.every(r=>r.visible+r.dimmed+r.unmapped===10));
 assert.ok(x.disclaimer.includes('does not indicate actual rack power'));
 return x;
};
const base=expectCount('normal',80,0,20);
assert.equal(base.entries[0].feed,'A');
assert.equal(base.entries[1].feed,'B');
assert.equal(base.entries[8].status,'unmapped');
assert.equal(base.entries[9].status,'unmapped');
const a=expectCount('a-loss',40,40,20);
assert.equal(a.entries[0].status,'dimmed');
assert.equal(a.entries[1].status,'visible');
assert.ok(a.rows.every(x=>x.visible===4&&x.dimmed===4&&x.unmapped===2));
const b=expectCount('b-loss',40,40,20);
assert.equal(b.entries[0].status,'visible');
assert.equal(b.entries[1].status,'dimmed');
const grid=expectCount('grid-loss',0,80,20);
assert.equal(grid.entries[8].status,'unmapped');
assert.equal(FLOOR100_ROUTE_SCENARIOS.length,4);
assert.throws(()=>buildFloor100Impact(racks,'invalid'),RangeError);
assert.throws(()=>buildFloor100Impact(racks.slice(0,4),'normal'),RangeError);
assert.equal(JSON.stringify(racks),before);
console.log(JSON.stringify({status:'PASS',rackCount:100,scenarios:FLOOR100_ROUTE_SCENARIOS.length,aLoss:a.counts,bLoss:b.counts,gridLoss:grid.counts,notRealTelemetry:true},null,2));
