import assert from 'node:assert/strict';
import {FLOOR100_POWER_PROFILE,FLOOR100_DEMO_PUE,FLOOR100_POWER_SCENARIOS,buildFloor100PowerModel} from '../floor100-power.mjs';
const racks=Array.from({length:100},(_,i)=>({id:'R'+String(i+1).padStart(3,'0'),row:Math.floor(i/10),column:i%10,kind:i%10<8?'compute':i%10===8?'fabric':'storage'}));
const original=JSON.stringify(racks),initial=buildFloor100PowerModel(racks);
assert.deepEqual(initial.kindCounts,{compute:80,fabric:10,storage:10});
assert.equal(FLOOR100_DEMO_PUE,1.20);
assert.deepEqual(FLOOR100_POWER_SCENARIOS,[60,80,100]);
assert.equal(FLOOR100_POWER_PROFILE.compute.estimatedKW,120);
assert.equal(initial.entries.length,100);
assert.equal(initial.totalKW,10020);
assert.equal(initial.totalW,10020000);
assert.equal(initial.peakKW,11760);
assert.equal(initial.peakW,11760000);
assert.equal(initial.facilityKW,12024);
assert.equal(initial.facilityW,12024000);
assert.equal(initial.averageKW,100.2);
assert.ok(initial.rows.every(r=>r.estimatedKW===1002&&r.estimatedW===1002000));
assert.deepEqual(initial.entries.slice(7,10).map(e=>e.estimatedW),[120000,18000,24000]);
assert.ok(initial.entries.every(r=>r.estimatedW>=0&&r.peakW>=r.estimatedW&&r.feedA==='illustrative'&&r.feedB==='illustrative'));
assert.deepEqual(initial.entries.slice(7,10).map(e=>e.heatBand),['high','low','medium']);
const eighty=buildFloor100PowerModel(racks,80);
assert.equal(eighty.totalKW,8016);assert.equal(eighty.facilityKW,9619.2);assert.equal(eighty.entries[0].estimatedW,96000);
const sixty=buildFloor100PowerModel(racks,60);
assert.equal(sixty.totalKW,6012);assert.equal(sixty.entries[0].estimatedW,72000);
assert.equal(sixty.entries[0].heatBand,'medium');
assert.equal(buildFloor100PowerModel(racks,100,1).facilityKW,10020);
assert.throws(()=>buildFloor100PowerModel(racks,101),RangeError);
assert.throws(()=>buildFloor100PowerModel(racks,80,.99),RangeError);
assert.throws(()=>buildFloor100PowerModel(racks,100,3),RangeError);
assert.throws(()=>buildFloor100PowerModel(racks.slice(0,10)),RangeError);
const dupe=racks.map(r=>({...r}));dupe[1].id=dupe[0].id;
assert.throws(()=>buildFloor100PowerModel(dupe),RangeError);
assert.equal(original,JSON.stringify(racks));
assert.ok(initial.disclaimer.includes('no actual rack watt reading'));
console.log(JSON.stringify({status:'PASS',racks:100,estimatedITWatts:initial.totalW,facilityWatts:initial.facilityW,peakWatts:initial.peakW,wattsPerRow:initial.rows[0].estimatedW,loadScenarios:FLOOR100_POWER_SCENARIOS,source:'assumed demonstration profiles, not official NVIDIA rack draw'},null,2));
